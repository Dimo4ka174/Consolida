        public static async Task Seed(AppDbContext context, ILogger logger)
        {
            if (context.CodesTNVD.Any())
            {
                logger.LogDebug("CodesTNVD already exist, skipping creation");
                return;
            }

            var codes = Codes.Select(c => new CodeTNVD
            {
                Name = c.Name,
                Rate = c.Rate,
                IsDeleted = false
            }).ToList();

            await context.CodesTNVD.AddRangeAsync(codes);
            await context.SaveChangesAsync();

            logger.LogInformation("Created {Count} CodeTNVD records", codes.Count);
        }
